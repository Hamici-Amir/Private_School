/**
 * Fictional teaching staff of the school. Every teacher references classes
 * from the students class constants through `classIds`; the 16 school classes
 * are each covered by the suitable subject teachers. All data is invented.
 */

interface TeacherSeed {
  id: string
  teacherNumber: string
  firstName: string
  lastName: string
  gender: TeacherGender
  /** ISO date (yyyy-mm-dd). */
  birthDate: string
  /** Digits only (e.g. "0550123456"); display formatting happens in utils. */
  phone: string
  specialty: TeacherSpecialty
  qualification: TeacherQualification
  /** ISO date (yyyy-mm-dd). */
  hireDate: string
  classIds: string[]
  status: TeacherStatus
  /** ISO date (yyyy-mm-dd). */
  createdAt: string
  firstNameAr?: string
  lastNameAr?: string
  email?: string
  address?: string
  city?: string
  notes?: string
}

function makeTeacher(seed: TeacherSeed): Teacher {
  return {
    firstNameAr: undefined,
    lastNameAr: undefined,
    email: undefined,
    address: undefined,
    city: undefined,
    notes: undefined,
    ...seed,
  }
}

